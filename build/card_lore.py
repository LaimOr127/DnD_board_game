def _state_text(*sources):
    lines = []
    names = []
    for source in sources:
        if source:
            trigger, states = source
            lines.append(trigger)
            names.extend(states)
    return ' '.join(lines + [_STATE_RULES[state] for state in dict.fromkeys(names)])


