def current(table, story):
    party = table["party"]
    if (story["page"] == "epilogue" or table["scene"] or party.get("weatherDue")
            or party.get("fightDue") or not E.claimed(table)):
        return None
    realm = party["realm"]
    meeting = MEETINGS[realm]
    record = story.get("meetings", {}).get(str(realm), {})
    stage = "settled" if "choice" in record else "open" if record else "rumour"
    view = {"realm": realm, "kingdom": E.realms[realm - 1][0], "title": meeting.title,
            "npc": meeting.npc, "stage": stage, "text": meeting.hook, "voices": [], "choices": []}
    if stage == "open":
        view.update(text=meeting.secret,
                    voices=[line for hero, line in meeting.voices.items() if hero in E.claimed(table)],
                    choices=[{"id": key, "label": path.label} for key, path in meeting.paths.items()])
    elif stage == "settled":
        view["text"] = meeting.paths[record["choice"]].immediate
    return view


def choose(table, seat, story, action):
    view = current(table, story)
    if not view or view["realm"] != action.get("realm") or table["party"]["chapter"] != action.get("chapter"):
        return E.fail(table, "Отряд уже в другом месте или занят. Сверьтесь с картой.")
    realm = view["realm"]
    key = str(realm)
    choice = action.get("choice")
    if view["stage"] == "rumour" and choice == "listen":
        story.setdefault("meetings", {})[key] = {"opened": table["party"]["chapter"]}
        E.log(table, seat, "scene", f"{view['kingdom']}. {view['npc']} рассказывает о встрече «{view['title']}».")
    elif view["stage"] == "open" and isinstance(choice, str) and choice in MEETINGS[realm].paths:
        path = MEETINGS[realm].paths[choice]
        witnesses = [h for h in MEETINGS[realm].voices if h in E.claimed(table)]
        story["meetings"][key].update(choice=choice, chapter=table["party"]["chapter"], witnesses=witnesses)
        E.log(table, seat, "gm", f"{view['title']}. {path.label}. {path.immediate}")
    else:
        return E.fail(table, "Это действие встречи уже недоступно.")
    table["story"] = story
    return {"ok": True}


def chronicle(story):
    entries = []
    for key, record in story.get("meetings", {}).items():
        if "choice" not in record:
            continue
        realm = int(key)
        meeting = MEETINGS[realm]
        path = meeting.paths[record["choice"]]
        entries.append({"kingdom": E.realms[realm - 1][0], "title": meeting.title, "npc": meeting.npc,
                        "chapter": record["chapter"], "choice": path.label, "text": path.immediate,
                        "witnesses": [E.HERO_BY[h]["name"] for h in record["witnesses"]],
                        "news": record.get("news", ""), "arrival": record.get("arrival", "")})
    return entries


