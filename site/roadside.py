def gift(party, realm, kind):
    if kind == "supply":
        if party["supplies"] >= 6:
            return "Припасы отряда полны. Гостинец разделили в дороге."
        party["supplies"] += 1
        return "У отряда на один припас больше."
    if kind == "silver":
        party["silver"] += 2
        return "В общей казне прибавилось два серебра."
    if kind == "glory":
        if party["glory"][realm - 1] >= 4:
            return "Ваша слава в этом королевстве уже достигла высшей отметки."
        party["glory"][realm - 1] += 1
        return "Местная слава выросла на один."
    if kind == "street":
        party["street"] += 1
        return "Прибавился голос улицы."
    return ""


def deliver(table, seat, story, epilogue=False):
    party = table["party"]
    for key, record in story.get("meetings", {}).items():
        if ("choice" not in record or "arrival" in record
                or (record["chapter"] >= party["chapter"] and not epilogue)):
            continue
        realm = int(key)
        choice = record["choice"]
        path = MEETINGS[realm].paths[choice]
        text, reward = path.news, path.gift
        late = LATE_NEWS.get((realm, choice))
        if late and (epilogue or party["chapter"] > late[0]):
            _, text, reward = late
        record["news"] = " ".join(filter(None, (text, gift(party, realm, reward))))
        record["arrival"] = "Эпилог" if epilogue else f"Глава {party['chapter']}"
        E.log(table, seat, "gm", "Весть из королевства " + E.realms[realm - 1][0] + ". " + record["news"])


def heard(story, realm, choice):
    record = story.get("meetings", {}).get(str(realm), {})
    return record.get("choice") == choice and bool(record.get("arrival"))
